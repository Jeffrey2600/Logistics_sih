// The speech recogniser needs a BCP-47 tag, not our two-letter key. Assamese
// has thin recogniser support, so it falls back to Bengali, which is the
// closest widely-supported language and shares the script.
const SPEECH_LOCALE = {
  en: "en-IN", hi: "hi-IN", as: "bn-IN", bn: "bn-IN", ne: "ne-NP",
};

let current = "en";

function t(key, vars) {
  const table = STRINGS[current] || STRINGS.en;
  // Falling back to English beats showing a raw key: a missing translation
  // should degrade to a language most users here can still read.
  let value = table[key] != null ? table[key] : STRINGS.en[key];
  if (value == null) {
    console.warn(`missing translation for "${key}"`);
    return key;
  }
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.split("{" + name + "}").join(replacement);
    }
  }
  return value;
}

function currentLanguage() { return current; }
function speechLocale() { return SPEECH_LOCALE[current] || "en-IN"; }

// Walks the static markup. Anything generated by app.js calls t() directly at
// render time instead, and is re-rendered when the language changes.
function applyTranslations(root) {
  (root || document).querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = t(element.dataset.i18n);
  });
  (root || document).querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    element.placeholder = t(element.dataset.i18nPlaceholder);
  });
  (root || document).querySelectorAll("[data-i18n-title]").forEach((element) => {
    element.title = t(element.dataset.i18nTitle);
  });
  document.documentElement.lang = current;
}

function setLanguage(code) {
  if (!STRINGS[code]) return false;
  current = code;
  try { localStorage.setItem("ner.lang", code); } catch (_) { /* private mode */ }
  applyTranslations();
  return true;
}

function restoreLanguage() {
  let saved = null;
  try { saved = localStorage.getItem("ner.lang"); } catch (_) { /* private mode */ }
  if (saved && STRINGS[saved]) current = saved;
  return current;
}
